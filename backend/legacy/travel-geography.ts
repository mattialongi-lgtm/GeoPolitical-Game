export const haversineDistance = (lat1: number, lon1: number, lat2: number, lon2: number): number => {
  const R = 6371;
  const dLat = (lat2 - lat1) * Math.PI / 180;
  const dLon = (lon2 - lon1) * Math.PI / 180;
  const a = Math.sin(dLat / 2) ** 2 +
    Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) *
    Math.sin(dLon / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
};

export const TRAVEL_MIN_MINUTES = 1;
export const TRAVEL_MAX_MINUTES = 60;
export const TRAVEL_KM_PER_MINUTE = 100;
export const TRAVEL_DEFAULT_MS = 2 * 60 * 1000;

export const calculateTravelTimeMs = (fromIso2: string, toIso2: string): number => {
  const from = COUNTRY_COORDS[fromIso2.toUpperCase()];
  const to = COUNTRY_COORDS[toIso2.toUpperCase()];
  if (!from || !to) return TRAVEL_DEFAULT_MS;
  const distKm = haversineDistance(from[0], from[1], to[0], to[1]);
  const minutes = Math.max(
    TRAVEL_MIN_MINUTES,
    Math.min(TRAVEL_MAX_MINUTES, Math.round(distKm / TRAVEL_KM_PER_MINUTE))
  );
  return minutes * 60 * 1000;
};
